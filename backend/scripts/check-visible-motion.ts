import 'dotenv/config';
import {setMotion} from './helpers/motion';
import {chromium,type Locator} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile,copyFile} from 'node:fs/promises';
const origin='http://127.0.0.1:3001';
const dir='artifacts/qa/visible-motion';
await mkdir(dir,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const report:Record<string,unknown>={};
async function sample(locator:Locator){return await locator.evaluate(el=>new Promise<{time:number;opacity:number;transform:string}[]>(resolve=>{const samples:{time:number;opacity:number;transform:string}[]=[];const start=performance.now();const timer=setInterval(()=>{const css=getComputedStyle(el);samples.push({time:performance.now()-start,opacity:Number(css.opacity),transform:css.transform});if(performance.now()-start>=260){clearInterval(timer);resolve(samples);}},16);}));}
function assertMoving(samples:{opacity:number;transform:string}[],label:string){assert(new Set(samples.map(s=>`${s.opacity}:${s.transform}`)).size>2,label+' must change over actual rendered frames');report[label]=samples;}
try{
 const auth=await browser.newContext();
 const login=await auth.request.post(origin+'/api/auth/login',{headers:{origin},data:{username:'quanly',password:process.env.BOOTSTRAP_PASSWORD}});assert(login.ok());
 const session=await auth.storageState();await auth.close();
 const context=await browser.newContext({storageState:session,viewport:{width:1440,height:900},reducedMotion:'no-preference',recordVideo:{dir:dir+'/raw',size:{width:1440,height:900}}});
 const page=await context.newPage();
 await page.goto(origin+'/dashboard');await page.waitForFunction(()=>document.querySelectorAll('.chart-loading').length===0);
 await setMotion(page,'full');
 await page.waitForTimeout(900);
 await page.locator('.sidebar').getByRole('link',{name:'Đơn hàng',exact:true}).click();
 await page.getByRole('heading',{name:'Đơn hàng',exact:true}).waitFor();
 assertMoving(await sample(page.locator('.page-heading')),'route-content-arrival');
 await page.waitForTimeout(800);
 await page.locator('.sidebar').getByRole('link',{name:'Tổng quan',exact:true}).click();
 await page.getByRole('heading',{name:'Tổng quan kinh doanh',exact:true}).waitFor();
 assertMoving(await sample(page.locator('.dashboard-main-grid')),'dashboard-group-arrival');
 await page.waitForTimeout(900);
 await page.getByRole('button',{name:'Đọc số liệu',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 assertMoving(await sample(page.getByRole('dialog')),'drawer-open');
 await page.waitForTimeout(600);
 await page.screenshot({path:dir+'/drawer-open.png'});
 await page.keyboard.press('Escape');
 const closing=await sample(page.locator('.data-drawer[data-state=closed]')).catch(()=>[]);
 assert(closing.length>1,'exit keeps dialog mounted while it animates');report['drawer-close']=closing;
 await page.getByRole('dialog').waitFor({state:'hidden'});
 await page.waitForTimeout(600);
 await page.getByLabel('Kỳ báo cáo',{exact:true}).selectOption('7');
 await page.locator('.chart-data-transition[data-points="7"]').waitFor();
 assertMoving(await sample(page.locator('.chart-data-transition')),'chart-period-change');
 await page.waitForTimeout(900);
 await page.getByLabel('Kỳ báo cáo',{exact:true}).selectOption('30');
 await page.locator('.chart-data-transition[data-points="30"]').waitFor();
 await page.waitForTimeout(900);
 await page.goto(origin+'/orders/DEMO-HAI-KHO');
 await page.getByRole('tab',{name:'Thu / hoàn',exact:true}).click();
 assertMoving(await sample(page.getByRole('tabpanel')),'order-tab-change');
 await page.waitForTimeout(600);
 await page.getByRole('tab',{name:'Hàng & kiện',exact:true}).click();
 await page.waitForTimeout(500);
 await page.getByRole('button',{name:'Tìm kho phù hợp',exact:true}).click();
 await page.locator('.allocation-parcel').nth(1).waitFor();
 assertMoving(await sample(page.locator('.allocation-parcel').nth(1)),'allocation-second-parcel');
 await page.waitForTimeout(1000);
 await page.screenshot({path:dir+'/allocation-final.png',fullPage:true});
 await page.getByRole('button',{name:'Xem lại chuyển động',exact:true}).click();
 await page.waitForTimeout(1200);
 const video=page.video();await context.close();
 if(video){await video.saveAs(dir+'/oms-motion.webm');await mkdir('public/demo',{recursive:true});await copyFile(dir+'/oms-motion.webm','public/demo/oms-motion.webm');}
 const reduced=await browser.newContext({storageState:session,viewport:{width:1366,height:768},reducedMotion:'reduce'});
 const rp=await reduced.newPage();await rp.goto(origin+'/dashboard');await rp.waitForFunction(()=>document.querySelectorAll('.chart-loading').length===0);await rp.waitForTimeout(600);
 const autoDuration=await rp.locator('.page-heading').evaluate(e=>getComputedStyle(e).animationDuration);
 assert(parseFloat(autoDuration)<.001,'default obeys OS reduced motion');report.autoReducedDuration=autoDuration;
 await setMotion(rp,'full');
 await rp.locator('.sidebar').getByRole('link',{name:'Đơn hàng',exact:true}).click();
 await rp.getByRole('heading',{name:'Đơn hàng',exact:true}).waitFor();
 assertMoving(await sample(rp.locator('.page-heading')),'explicit-full-overrides-system-reduce');
 await setMotion(rp,'reduced');await rp.reload();await rp.getByRole('heading',{name:'Đơn hàng',exact:true}).waitFor();
 assert.equal(await rp.evaluate(()=>document.documentElement.dataset.motion),'reduced');
 const manualDuration=await rp.locator('.page-heading').evaluate(e=>getComputedStyle(e).animationDuration);
 assert(parseFloat(manualDuration)<.001);report.manualReducedDuration=manualDuration;report.preferencePersistsAcrossReload=true;
 await reduced.close();
 await writeFile(dir+'/check.json',JSON.stringify(report,null,2));
 console.log('PASS actual frame changes: route, dashboard groups, chart filter, drawer, tab, allocation; OS reduce respected, explicit full works, manual reduce persists. Video public/demo/oms-motion.webm');
}finally{await browser.close();}
